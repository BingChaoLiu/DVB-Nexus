"""Conformance: the registered ``biss-mode-e-derive`` golden vector
(SPEC-611 §11/§12 AC-611-02, SPEC-506 §4-§8, ticket #127).

Independent truth: the registered trio (sha256-gated) whose bytes were
generated by ``tools/make_golden_biss_mode_e.py`` — the J.96 §9.3/§8 and
TS 103 127 §6.3 algorithms re-implemented inline with pycryptodome
primitives (NO ``src/`` involvement in generation).  The runtime
implementation (``ts.biss.mode_e`` / ``ts.biss.cissa``) is cross-checked
against it:

- the full Mode E derivation chain (ESW + Injected ID → session word →
  CW → CISSA key) reproduces the registered manifest values;
- the declared chain clears the registered stream (structural self-check
  verdicts) and the scramble/descramble roundtrip reproduces the
  registered bytes exactly (determinism);
- the per-packet restart independence (SPEC-611 §11: 改包 k 不影响包
  k+1 输出) holds over the registered bytes;
- the digest pin (this file's frozen sha256 row — the additive
  #127 registration record; the frozen first-batch table is untouched,
  brief §3.6-5).

Crypto dependency: pycryptodome — absent → the module skips loudly with
the SPEC-611 §8 dependency reason (honest NOT RUN; the CI face installs
pycryptodome, so this runs green there — no DLL face).
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import replace
from pathlib import Path

import pytest

try:
    import Crypto.Cipher.AES  # noqa: F401 — the dependency probe
except ImportError:
    pytest.skip(
        "pycryptodome absent — SPEC-611 §8 dependency face (Mode E "
        "derivation / CISSA); conformance honestly NOT RUN without it",
        allow_module_level=True,
    )

from ts.biss.biss1 import TSC_EVEN_KEY, derive_cw as derive_cw_from_sw
from ts.biss.cissa import descramble, scramble
from ts.biss.mode_e import derive_ciss_key, derive_sw
from ts.packet import TSPacket

VECTOR_ID = "biss-mode-e-derive"

#: The frozen byte identity of this registration (SPEC-506 §6: 变更 =
#: 重新登记 + 批准).  Additive #127 row — the first-batch frozen table
#: (tests/conformance/test_first_batch_registry.py) is untouched.
FROZEN_SHA256 = (
    "eda260a4e579a6d209f94fb4a71e4130ae23e58c29e564b77094baf069218a60"
)


def _manifest(golden_root: Path) -> dict:
    return json.loads(
        (golden_root / VECTOR_ID / "manifest.json").read_text(
            encoding="utf-8"
        )
    )


def _packets(ts_bytes: bytes) -> "list[TSPacket]":
    return [
        TSPacket.from_bytes(ts_bytes[i * 188:(i + 1) * 188])
        for i in range(len(ts_bytes) // 188)
    ]


class TestRegistrationShape:
    def test_vector_is_registered_bit_level(self, golden_loader) -> None:
        vector = golden_loader.load(VECTOR_ID)
        assert vector.kind == "bit_level"
        assert "SPEC-611" in vector.related_specs
        assert vector.packet_count == 6
        assert len(vector.ts_bytes) == 188 * 6

    def test_digest_pin_matches_registration(self, golden_loader) -> None:
        """SPEC-506 §6: the sha256 IS the identity — the frozen row in
        this file, the manifest and the bytes must agree."""
        vector = golden_loader.load(VECTOR_ID)
        actual = hashlib.sha256(vector.ts_bytes).hexdigest()
        assert actual == FROZEN_SHA256
        manifest = _manifest(Path(golden_loader.root))
        assert manifest["sha256"].removeprefix("sha256:") == FROZEN_SHA256

    def test_expectations_pin_scrambled_slots(self, golden_loader) -> None:
        vector = golden_loader.load(VECTOR_ID)
        for index, entry in enumerate(vector.expectations):
            assert entry["event_type"] == "ts.packet_batch_observed"
            assert entry["locator"]["packet_index"] == index
            assert entry["detail"]["pid"] == 0x0100
            assert entry["detail"]["scrambling"] == 2  # TSC `10`


class TestDerivationChainCrossCheck:
    """The runtime ``ts.biss.mode_e`` chain against the independently
    generated manifest values (AC-611-01/02: 接口在位 + 确定性钉扎)."""

    def test_derive_sw_reproduces_the_registered_session_word(
        self, golden_loader
    ) -> None:
        manifest = _manifest(Path(golden_loader.root))
        biss = manifest["biss"]
        assert biss["mode"] == "E"
        session_word = derive_sw(biss["encrypted_sw"], biss["injected_id"])
        assert session_word == biss["derived_session_word"]
        # Case-insensitive wire shapes stay deterministic.
        assert derive_sw(
            biss["encrypted_sw"].lower(), biss["injected_id"].lower()
        ) == session_word

    def test_derived_cw_lands_on_the_j96_formula(self, golden_loader) -> None:
        manifest = _manifest(Path(golden_loader.root))
        biss = manifest["biss"]
        cw = derive_cw_from_sw(biss["derived_session_word"])[1]
        assert cw.hex().upper() == biss["derived_cw"]
        from ts.biss.mode_e import derive_cw

        assert derive_cw(biss["encrypted_sw"], biss["injected_id"])[
            1
        ] == cw

    def test_ciss_key_composition_is_the_pinned_rule(
        self, golden_loader
    ) -> None:
        manifest = _manifest(Path(golden_loader.root))
        biss = manifest["biss"]
        cw = bytes.fromhex(biss["derived_cw"].lower())
        assert derive_ciss_key(biss["encrypted_sw"], biss["injected_id"]) == (
            cw + cw
        )
        assert biss["ca_pid"] == 0x1FFF
        assert biss["ca_system_id"] == 0x2602  # BISS2 (SPEC-611 §2.1)
        assert biss["pid_scope"] == [0x0100]


class TestRuntimeCrossCheck:
    def test_registered_packets_parse_strict_with_tsc_marked(
        self, golden_loader
    ) -> None:
        vector = golden_loader.load(VECTOR_ID)
        for index, packet in enumerate(_packets(vector.ts_bytes)):
            assert packet.pid == 0x0100
            assert packet.transport_scrambling_control == TSC_EVEN_KEY
            assert packet.continuity_counter == index

    def test_declared_chain_clears_the_registered_stream(
        self, golden_loader
    ) -> None:
        """Every packet's structural self-check passes under the derived
        chain (the CRC-protected PSI sections give real verdicts)."""
        vector = golden_loader.load(VECTOR_ID)
        manifest = _manifest(Path(golden_loader.root))
        ciss_key = derive_ciss_key(
            manifest["biss"]["encrypted_sw"],
            manifest["biss"]["injected_id"],
        )
        _clear, checks = descramble(
            _packets(vector.ts_bytes), ciss_key, (0x0100,)
        )
        assert checks, "every packet is structurally self-checked"
        assert all(check.ok for check in checks)
        assert all(
            check.self_check_kind == "psi_section_crc32"
            for check in checks
        )

    def test_roundtrip_matches_registered_bytes(self, golden_loader) -> None:
        """scramble(descramble(golden)) == golden — the runtime CISSA
        face reproduces the registered bytes exactly (determinism, L3
        regression over an L1 truth)."""
        vector = golden_loader.load(VECTOR_ID)
        manifest = _manifest(Path(golden_loader.root))
        ciss_key = derive_ciss_key(
            manifest["biss"]["encrypted_sw"],
            manifest["biss"]["injected_id"],
        )
        clear, _checks = descramble(
            _packets(vector.ts_bytes), ciss_key, (0x0100,)
        )
        rescrambled = scramble(clear, ciss_key, (0x0100,))
        assert b"".join(p.to_bytes() for p in rescrambled) == vector.ts_bytes

    def test_per_packet_restart_independence_over_registered_bytes(
        self, golden_loader
    ) -> None:
        """SPEC-611 §11 template: 改包 k 不影响包 k+1 输出 — flipping a
        clear payload byte of packet k changes ONLY packet k's scramble
        output; every other packet reproduces the registered bytes."""
        vector = golden_loader.load(VECTOR_ID)
        manifest = _manifest(Path(golden_loader.root))
        ciss_key = derive_ciss_key(
            manifest["biss"]["encrypted_sw"],
            manifest["biss"]["injected_id"],
        )
        packets = _packets(vector.ts_bytes)
        clear, _checks = descramble(packets, ciss_key, (0x0100,))
        modified = list(clear)
        victim = 2
        modified[victim] = replace(
            modified[victim],
            payload=bytes([modified[victim].payload[0] ^ 0xFF])
            + modified[victim].payload[1:],
        )
        rescrambled = scramble(modified, ciss_key, (0x0100,))
        for index in range(len(packets)):
            if index == victim:
                assert (
                    rescrambled[index].to_bytes() != packets[index].to_bytes()
                )
            else:
                assert (
                    rescrambled[index].to_bytes() == packets[index].to_bytes()
                ), "packet independence: only the modified packet changed"

    def test_clear_tail_rule_on_registered_bytes(self, golden_loader) -> None:
        """TS 103 127 §6.3.2 example 1: no AF ⇒ the last 8 payload bytes
        of every registered packet stayed clear — descrambling leaves
        them byte-identical (they were never encrypted)."""
        vector = golden_loader.load(VECTOR_ID)
        manifest = _manifest(Path(golden_loader.root))
        ciss_key = derive_ciss_key(
            manifest["biss"]["encrypted_sw"],
            manifest["biss"]["injected_id"],
        )
        for packet in _packets(vector.ts_bytes):
            assert len(packet.payload) == 184
            clear, _checks = descramble([packet], ciss_key, (0x0100,))
            assert clear[0].payload[176:] == packet.payload[176:]
            assert clear[0].payload[:176] != packet.payload[:176]
