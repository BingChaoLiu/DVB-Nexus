"""Conformance: the registered ``biss-j96-mode1`` golden vector
(SPEC-610 §11 / SPEC-506 §4-§8, ticket #126).

Independent truth: the registered trio (sha256-gated) whose bytes were
generated by ``tools/make_golden_biss_j96.py`` from the ITU-T J.96 §8
example session word through the pure-Python CSA1 oracle (research #106
port — NO ``src/`` involvement in generation).  The runtime
implementation (``ts.biss.biss1``) is cross-checked against it:

- the J.96 SW→CW derivation pin (the published standard constant);
- the descramble structural self-check (CRC-protected PSI section) with
  the declared key (oracle backend — the DLL binding is separately
  cross-checked in the adapter suite and cross-verified here when the
  DLL is present);
- the scramble/descramble roundtrip and determinism pins.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from adapters.dvbcsa import DvbcsaBatchCipher
from ts.biss.biss1 import (
    TSC_EVEN_KEY,
    descramble,
    derive_cw,
    key_fingerprint,
    scramble,
)
from ts.packet import TSPacket
from tests._support.csa1_oracle import Csa1Oracle

VECTOR_ID = "biss-j96-mode1"

ORACLE = Csa1Oracle()


def _manifest(golden_root: Path) -> dict:
    return json.loads(
        (golden_root / VECTOR_ID / "manifest.json").read_text(
            encoding="utf-8"
        )
    )


def _packets(ts_bytes: bytes) -> "list[TSPacket]":
    return [
        TSPacket.from_bytes(ts_bytes[i * 188:(i + 1) * 188])
        for i in range(len(ts_bytes) // 188)
    ]


class TestRegistrationShape:
    def test_vector_is_registered_bit_level(self, golden_loader) -> None:
        vector = golden_loader.load(VECTOR_ID)
        assert vector.kind == "bit_level"
        assert "SPEC-610" in vector.related_specs
        assert vector.packet_count == 6
        assert len(vector.ts_bytes) == 188 * 6

    def test_expectations_pin_scrambled_slots(self, golden_loader) -> None:
        vector = golden_loader.load(VECTOR_ID)
        for index, entry in enumerate(vector.expectations):
            assert entry["event_type"] == "ts.packet_batch_observed"
            assert entry["locator"]["packet_index"] == index
            assert entry["detail"]["pid"] == 0x0100
            assert entry["detail"]["scrambling"] == 2  # TSC `10`

    def test_manifest_records_j96_derivation(self, golden_loader) -> None:
        manifest = _manifest(Path(golden_loader.root))
        biss = manifest["biss"]
        assert biss["mode"] == "1"
        # The J.96 §8 derivation pin lives in the registered manifest —
        # the runtime implementation is cross-checked against it below.
        odd, even = derive_cw(biss["session_word"])
        assert even.hex().upper() == biss["derived_cw"]
        assert odd == even  # Mode 1: one CW, both parity slots
        assert biss["ca_pid"] == 0x1FFF
        assert biss["pid_scope"] == [0x0100]


class TestRuntimeCrossCheck:
    def test_registered_packets_strict_parse_with_tsc_even(
        self, golden_loader
    ) -> None:
        vector = golden_loader.load(VECTOR_ID)
        for index, packet in enumerate(_packets(vector.ts_bytes)):
            assert packet.pid == 0x0100
            assert packet.transport_scrambling_control == TSC_EVEN_KEY
            assert packet.continuity_counter == index

    def test_descramble_with_declared_key_passes_psi_crc(
        self, golden_loader
    ) -> None:
        """The declared key clears the stream: every PSI section CRC-32
        self-check passes (the structural self-check verdict surface)."""
        vector = golden_loader.load(VECTOR_ID)
        manifest = _manifest(Path(golden_loader.root))
        session_word = manifest["biss"]["session_word"]
        clear, checks = descramble(
            _packets(vector.ts_bytes), session_word, (0x0100,),
            backend=ORACLE,
        )
        assert checks, "every packet is structurally self-checked"
        assert all(check.ok for check in checks)
        assert all(
            check.self_check_kind == "psi_section_crc32" for check in checks
        )

    def test_scramble_descramble_roundtrip_matches_registered_bytes(
        self, golden_loader
    ) -> None:
        """scramble(descramble(golden)) == golden — the oracle roundtrip
        reproduces the registered bytes exactly (determinism, L3)."""
        vector = golden_loader.load(VECTOR_ID)
        manifest = _manifest(Path(golden_loader.root))
        session_word = manifest["biss"]["session_word"]
        clear, _ = descramble(
            _packets(vector.ts_bytes), session_word, (0x0100,),
            backend=ORACLE,
        )
        rescrambled = scramble(clear, session_word, (0x0100,), backend=ORACLE)
        assert b"".join(p.to_bytes() for p in rescrambled) == vector.ts_bytes

    def test_key_fingerprint_is_stable_for_the_declared_key(
        self, golden_loader
    ) -> None:
        manifest = _manifest(Path(golden_loader.root))
        session_word = manifest["biss"]["session_word"]
        fingerprint = key_fingerprint(session_word)
        assert fingerprint.startswith("sha256:")
        assert fingerprint == key_fingerprint(session_word.lower())


class TestDllCrossVerification:
    """DLL-present cross-check of the oracle against libdvbcsa over the
    registered bytes.  CI (ubuntu) has no MSYS2/DLL: honestly NOT RUN via
    the dvbcsa_dll fixture skip (ADR-0011 §5, ruling §10-2)."""

    def test_dll_descramble_matches_oracle_on_registered_bytes(
        self, golden_loader, dvbcsa_dll
    ) -> None:
        vector = golden_loader.load(VECTOR_ID)
        manifest = _manifest(Path(golden_loader.root))
        session_word = manifest["biss"]["session_word"]
        cw = derive_cw(session_word)[1]
        payloads = [p.payload for p in _packets(vector.ts_bytes)]
        dll_cipher = DvbcsaBatchCipher(dvbcsa_dll.path)
        assert dll_cipher.decrypt_batch(payloads, cw) == ORACLE.decrypt_batch(
            payloads, cw
        )
        # ...and the DLL-cleared payloads re-encrypt to the registered
        # payload regions byte-for-byte (roundtrip across implementations).
        assert dll_cipher.encrypt_batch(
            list(dll_cipher.decrypt_batch(payloads, cw)), cw
        ) == tuple(payloads)
