"""First-batch golden vectors ``pat-minimal`` / ``pat-pmt-multi`` — assertions.

Conformance layer (SPEC-505 §3 / SPEC-506 §7 #2/#3).  Both vectors are
generated by TSDuck (tsxml → tstabcomp → tsp inject, the ticket-#3-tested
chain) and verified here by parsing with the self parser — the L2
``tsduck-generate→self-parse`` cross direction (SPEC-506 §5, #14 Q1).
"""

from __future__ import annotations

import pytest

from ts.packet import TSPacket
from ts.section_assembler import SectionAssembler
from ts.tables.pat import PAT_SECTION_POLICY, parse_pat_sections
from ts.tables.pmt import PMT_SECTION_POLICY, parse_pmt_sections

pytestmark = pytest.mark.conformance

PAT_MINIMAL_ID = "pat-minimal"
PAT_MULTI_ID = "pat-pmt-multi"


def _packets(vector) -> list[TSPacket]:
    return [
        TSPacket.from_bytes(vector.ts_bytes[offset : offset + 188])
        for offset in range(0, len(vector.ts_bytes), 188)
    ]


def _sections_on(vector, pid: int):
    assembler = SectionAssembler(pid, lambda table_id: PAT_SECTION_POLICY if table_id == 0 else PMT_SECTION_POLICY)
    sections = []
    for packet in _packets(vector):
        if packet.pid == pid:
            sections.extend(assembler.push(packet))
    assert assembler.flush() == []
    return sections


def _psi_packet_indices(vector, pid: int) -> list[int]:
    return [
        index
        for index, packet in enumerate(_packets(vector))
        if packet.pid == pid
    ]


# --- pat-minimal ---------------------------------------------------------------


def test_pat_minimal_shape_and_registration(golden_loader):
    vector = golden_loader.load(PAT_MINIMAL_ID)
    assert vector.kind == "generated_ts"
    assert vector.packet_count == 50
    assert len(vector.ts_bytes) == 50 * 188
    assert vector.verification is not None
    assert vector.verification.path == "tsduck-cross"
    assert vector.verification.direction == "tsduck-generate→self-parse"
    assert vector.generator_version and vector.generator_version.startswith("tsduck ")
    # Everything except the PAT and PMT packets is null stuffing.
    packets = _packets(vector)
    non_null = [p for p in packets if p.pid != 0x1FFF]
    assert [p.pid for p in non_null] == [0x0000, 0x1000]
    assert all(p.payload_unit_start_indicator for p in non_null)


def test_pat_minimal_pat_and_pmt_parse(golden_loader):
    vector = golden_loader.load(PAT_MINIMAL_ID)
    pat_table = parse_pat_sections(_sections_on(vector, 0x0000))
    assert pat_table.transport_stream_id == 1
    assert len(pat_table.programs) == 1
    assert pat_table.programs[0].program_number == 1
    assert pat_table.programs[0].program_map_pid == 0x1000

    pmt_table = parse_pmt_sections(_sections_on(vector, 0x1000))
    assert pmt_table.program_number == 1
    assert pmt_table.pcr_pid == 0x0100
    assert [(es.stream_type, es.elementary_pid) for es in pmt_table.streams] == [
        (0x1B, 0x0101)
    ]


def test_pat_minimal_expectations_match_parsed_tables(golden_loader):
    vector = golden_loader.load(PAT_MINIMAL_ID)
    entries = list(vector.expectations)
    assert [entry["locator"]["pid"] for entry in entries] == [0x0000, 0x1000]
    pat_detail = entries[0]["detail"]
    assert pat_detail["programs"] == [{"program_number": 1, "pmt_pid": 0x1000}]
    assert pat_detail["packet_index"] == _psi_packet_indices(vector, 0x0000)[0]
    pmt_detail = entries[1]["detail"]
    assert pmt_detail["streams"] == [{"stream_type": 0x1B, "pid": 0x0101}]
    assert pmt_detail["packet_index"] == _psi_packet_indices(vector, 0x1000)[0]


# --- pat-pmt-multi --------------------------------------------------------------


def test_pat_pmt_multi_shape_and_registration(golden_loader):
    vector = golden_loader.load(PAT_MULTI_ID)
    assert vector.kind == "generated_ts"
    assert vector.packet_count == 60
    assert len(vector.ts_bytes) == 60 * 188
    assert vector.verification is not None
    assert vector.verification.path == "tsduck-cross"
    packets = _packets(vector)
    non_null = [p for p in packets if p.pid != 0x1FFF]
    assert [p.pid for p in non_null] == [0x0000, 0x1000, 0x1100]


def test_pat_pmt_multi_two_programs_multiple_stream_types(golden_loader):
    vector = golden_loader.load(PAT_MULTI_ID)
    pat_table = parse_pat_sections(_sections_on(vector, 0x0000))
    assert pat_table.transport_stream_id == 1
    assert [(p.program_number, p.program_map_pid) for p in pat_table.programs] == [
        (1, 0x1000),
        (2, 0x1100),
    ]

    pmt1 = parse_pmt_sections(_sections_on(vector, 0x1000))
    assert pmt1.program_number == 1
    assert pmt1.pcr_pid == 0x0100
    assert [(es.stream_type, es.elementary_pid) for es in pmt1.streams] == [
        (0x1B, 0x0101),
        (0x0F, 0x0102),
    ]

    pmt2 = parse_pmt_sections(_sections_on(vector, 0x1100))
    assert pmt2.program_number == 2
    assert pmt2.pcr_pid == 0x0110
    assert [(es.stream_type, es.elementary_pid) for es in pmt2.streams] == [
        (0x02, 0x0111),
        (0x03, 0x0112),
    ]


def test_pat_pmt_multi_expectations_declare_three_tables(golden_loader):
    vector = golden_loader.load(PAT_MULTI_ID)
    entries = list(vector.expectations)
    assert [entry["locator"]["pid"] for entry in entries] == [0x0000, 0x1000, 0x1100]
    assert entries[0]["detail"]["programs"] == [
        {"program_number": 1, "pmt_pid": 0x1000},
        {"program_number": 2, "pmt_pid": 0x1100},
    ]
    assert entries[1]["detail"]["streams"] == [
        {"stream_type": 0x1B, "pid": 0x0101},
        {"stream_type": 0x0F, "pid": 0x0102},
    ]
    assert entries[2]["detail"]["streams"] == [
        {"stream_type": 0x02, "pid": 0x0111},
        {"stream_type": 0x03, "pid": 0x0112},
    ]
