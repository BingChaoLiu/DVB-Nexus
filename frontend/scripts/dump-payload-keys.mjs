// Generate the Phase 2 payload-keys constant module from the registry's
// same-source face (ticket #141 drift lock, the dto:sync chain pattern).
//
// The dump is performed IN THIS TREE at run time (never a committed
// snapshot, the dump-openapi.mjs posture): `python -I -c` — isolated
// mode ignores PYTHONPATH, so the cwd-relative sys.path.insert inside
// the dump code is the import mechanism (resolvePython/envWithTreeSrc
// still pin THIS tree's interpreter and UTF-8).  The registry's ordered
// face (``PHASE2_PAYLOAD_KEY_SETS``) is the #129 REPORT §2 display order —
// the gen module renders verbatim, so a reordering is a deliberate,
// test-pinned change (test_phase2_payload_key_sets.py).
//
// Usage: node scripts/dump-payload-keys.mjs [output.ts]
//   (default: frontend/src/features/monitor/journal/payloadKeys.gen.ts)
import { writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import path from "node:path";
import { envWithTreeSrc, resolvePython, TREE_ROOT, FRONTEND_ROOT } from "./lib/python.mjs";

const output =
  process.argv[2] ??
  path.join(FRONTEND_ROOT, "src", "features", "monitor", "journal", "payloadKeys.gen.ts");

// Pure-ASCII JSON through the spawned pipe (locale-independent, the
// dump-openapi.mjs discipline); the display order rides the JSON object
// insertion order (json.dumps preserves dict order).
const DUMP_CODE = [
  "import json,sys",
  "sys.path.insert(0,'src')",
  "from domain.observation.registry import PHASE2_PAYLOAD_KEY_SETS",
  "json.dump({k: list(v) for k, v in PHASE2_PAYLOAD_KEY_SETS.items()}, sys.stdout, indent=2)",
].join("; ");

const result = spawnSync(resolvePython(), ["-I", "-c", DUMP_CODE], {
  cwd: TREE_ROOT,
  encoding: "utf8",
  env: envWithTreeSrc({ PYTHONUTF8: "1" }),
});

if (result.status !== 0 || result.error) {
  console.error("dump-payload-keys: python failed:", result.stderr ?? result.error);
  process.exit(1);
}
let keySets;
try {
  keySets = JSON.parse(result.stdout);
} catch {
  console.error("dump-payload-keys: stdout is not valid JSON — interpreter or tree mismatch");
  console.error((result.stderr ?? "").slice(0, 2000));
  process.exit(1);
}

const entries = Object.entries(keySets)
  .map(
    ([eventType, keys]) =>
      `  "${eventType}": [\n${keys.map((k) => `    "${k}",`).join("\n")}\n  ],`,
  )
  .join("\n");

const module = `// GENERATED by scripts/dump-payload-keys.mjs from
// src/domain/observation/registry.py PHASE2_PAYLOAD_KEY_SETS — the
// same-source authority (ticket #141; the #129 REPORT §2 display order).
// DO NOT EDIT BY HAND: drift is locked by \`npm run payload-keys:check\`
// (regenerate + git diff, the dto:check pattern) and by the registry's
// import-time self-check against the frozen validator key sets.
// Keys ride the JSON insertion order = the backend display order.

export const PHASE2_PAYLOAD_KEYS = {
${entries}
} as const;
`;

writeFileSync(output, module, "utf8");
console.log(`payloadKeys.gen.ts written: ${Object.keys(keySets).length} event type(s)`);
